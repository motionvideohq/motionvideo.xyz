// Vendor the reicon.dev "Duotone (Beta)" glyphs for every reicon-react icon the
// site imports. reicon-react on npm only ships Outline and Filled; the duotone
// set lives in the reicon repo (data/icon-duotone.json, MIT). Icons without a
// duotone glyph fall back to their Outline glyph in `ReiconDuotone`.
//
//   pnpm icons:duotone
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE =
  "https://raw.githubusercontent.com/dqev/reicon/main/data/icon-duotone.json";
const root = fileURLToPath(new URL("..", import.meta.url));
const output = path.join(root, "src/components/ui/reicon-duotone-glyphs.ts");

// reicon-react names whose duotone glyph has a different key: the duotone set
// is a different family, so line icons map to their nearest duotone form.
const ALIASES = {
  Check: "check-circle",
  ChevronDown: "arrow-down2",
  ChevronLeft: "arrow-left2",
  ChevronRight: "arrow-right2",
  ChevronUp: "arrow-up2",
  EnvelopeCheck: "envelope-unread",
  Exit: "logout",
  Grid: "widget",
  Loader: "refresh",
  Plus: "add-circle",
  Search: "magnifier",
  Send: "plane",
  Sparkles: "stars",
  Xmark: "close-circle",
};

const kebab = (name) =>
  name
    .replaceAll(/(?<lower>[a-z\d])(?<upper>[A-Z])/gu, "$<lower>-$<upper>")
    .toLowerCase();

const sourceFiles = async (dir) => {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile() && /\.tsx?$/u.test(entry.name))
    .map((entry) => path.join(entry.parentPath, entry.name));
};

const used = new Set();
const files = await sourceFiles(path.join(root, "src"));
const texts = await Promise.all(files.map((file) => readFile(file, "utf-8")));
for (const text of texts) {
  for (const match of text.matchAll(/reicon-react\/icons\/(?<name>\w+)/gu)) {
    used.add(match.groups.name);
  }
}

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`Fetching ${SOURCE} failed with HTTP ${response.status}`);
}
const { icons, version } = await response.json();

const glyphs = {};
const missing = [];
for (const name of [...used].toSorted()) {
  const key = ALIASES[name] ?? kebab(name);
  const code = icons[key]?.code;
  if (code) {
    // Mark the half-opacity layer so the component can recolour or solidify it.
    glyphs[name] = code.replaceAll(
      'opacity="0.5"',
      'data-tone="secondary" opacity="0.5"'
    );
  } else {
    missing.push(name);
  }
}

const body = Object.entries(glyphs)
  .map(
    ([name, code]) => `  [${JSON.stringify(name)}, ${JSON.stringify(code)}],`
  )
  .join("\n");
await writeFile(
  output,
  `// Generated by scripts/vendor-reicon-duotone.mjs from reicon's duotone set
// (${SOURCE}, v${version}, MIT). Do not edit by hand: run \`pnpm icons:duotone\`.
// Keyed by reicon-react component name.
export const DUOTONE_GLYPHS: ReadonlyMap<string, string> = new Map([
${body}
]);
`
);
console.log(
  `${Object.keys(glyphs).length} duotone glyphs written. Outline fallback: ${missing.join(", ") || "none"}.`
);
